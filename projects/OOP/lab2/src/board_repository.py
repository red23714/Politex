class BoardRepository:
    """Выдаёт случайную головоломку заданной сложности.

    Головоломки с конфликтующими подсказками (в исходной программе это
    ESY 02 и HRD 03) отфильтровываются при создании репозитория.
    """

    def __init__(self, rng: Optional[random.Random] = None) -> None:
        self._rng = rng if rng is not None else random.Random()
        self._puzzles: Dict[Difficulty, List[List[str]]] = {
            difficulty: [
                rows for rows in puzzles
                if not Board.from_strings(rows).has_conflicts()
            ]
            for difficulty, puzzles in _PUZZLES.items()
        }

    def count(self, difficulty: Difficulty) -> int:
        """Количество доступных головоломок данной сложности."""
        return len(self._puzzles[difficulty])

    def get_board(self, difficulty: Difficulty) -> Board:
        """Возвращает копию случайной головоломки заданной сложности."""
        rows = self._rng.choice(self._puzzles[difficulty])
        return Board.from_strings(rows)

    def all_boards(self, difficulty: Difficulty) -> List[Board]:
        """Возвращает копии всех доступных головоломок данной сложности."""
        return [Board.from_strings(rows) for rows in self._puzzles[difficulty]]
