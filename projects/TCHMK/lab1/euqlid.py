def nod(a, b):
    r0, r1 = a, b
    x0, x1 = 1, 0
    y0, y1 = 0, 1

    i = 1
    while r0 % r1 != 0:
        print(i, " : ", r1, x1, y1)
        q = r0 // r1

        x0_old = x0
        y0_old = y0
        r0_old = r0

        x0 = x1
        x1 = x0_old - q * x1

        y0 = y1
        y1 = y0_old - q * y1

        r0 = r1
        r1 = r0_old % r1

        i += 1

    return x1, y1, r1


