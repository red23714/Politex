def jacobi_symbol(a, n):
    # Свойство периодичности: (a / n) = (a % n / n)
    a %= n
    result = 1

    while a != 0:
        # Извлекаем все двойки из верхнего аргумента (свойство мультипликативности)
        while a % 2 == 0:
            a //= 2
            # Если n ≡ 3 или 5 (mod 8), то (2 / n) = -1
            if n % 8 in (3, 5):
                result = -result

        # Закон квадратичной взаимности: меняем местами числитель и знаменатель
        a, n = n, a

        # Если оба числа ≡ 3 (mod 4), знак меняется
        if a % 4 == 3 and n % 4 == 3:
            result = -result

        # Снова приводим по модулю
        a %= n

    # Если n стал равен 1, то НОД(исходных чисел) был 1, возвращаем результат.
    # Если n > 1, значит у чисел был общий делитель, символ Якоби равен 0.
    return result if n == 1 else 0

def test_soloveya(n):
    a = random.randint(2, n - 2)
    r = pow(a, (n - 1) // 2, n)

    if(r != 1 and r != n - 1):
        print("Число n составное")
        return

    s = jacobi_symbol(a, n)

    if(r != (s % n)):
        print("Число n составное")
        return

    print("Число n, вероятно, простое")

