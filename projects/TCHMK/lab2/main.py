# порядок числа a по модулю m это степень l при которой a ^ l сравнимо с единицей (mod m)
def test_ferma(n):
    a = random.randint(2, n - 2)
    r = pow(a, n - 1, n)
    if(r == 1):
        print("Число n, вероятно, простое")
    else:
        print("Число n составное")

